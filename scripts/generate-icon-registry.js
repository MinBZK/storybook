/**
 * Generates a static icon registry from SVG files.
 * This replaces the Vite-specific import.meta.glob pattern so that
 * nldd-icon works with both Vite (dev) and plain tsc (per-component build).
 *
 * Output: src/components/content/icon/icon-registry.ts
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const iconsDir = resolve(__dirname, '../src/components/content/icon/icons');
const outputFile = resolve(__dirname, '../src/components/content/icon/icon-registry.ts');

const iconNames = readdirSync(iconsDir)
	.filter(f => f.endsWith('.svg'))
	.map(f => f.slice(0, -4))
	.sort();

const entries = iconNames.map(name => {
	const svg = readFileSync(resolve(iconsDir, `${name}.svg`), 'utf-8').trim();
	return `\t['${name}', ${JSON.stringify(svg)}]`;
});

const output = `// Auto-generated by scripts/generate-icon-registry.js — do not edit manually.

export const iconRegistry = new Map<string, string>([
${entries.join(',\n')},
]);
`;

writeFileSync(outputFile, output, 'utf-8');
console.log(`Generated icon registry with ${iconNames.length} icons → ${outputFile}`);
