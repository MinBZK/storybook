/**
 * Generates dist/types/vue.d.ts from custom-elements.json.
 *
 * Vue needs the tags declared in GlobalComponents to type-check a template.
 * Written here rather than taken from custom-element-vuejs-integration, because
 * that generator emits names Vue does not look up: attributes only in their
 * kebab form, and events as "on" plus the raw name. A template writing
 * `week-numbers` or `@change` therefore failed to compile, which is precisely
 * what a consumer writes. The fixture in type-tests/vue proves the difference.
 *
 * Names emitted per attribute:
 *   week-numbers   the attribute as written in markup
 *   weekNumbers    what Vue normalises it to before looking up the prop
 *
 * And per event: onChange, because Vue turns @change into that prop.
 *
 * Usage: node scripts/generate-vue-types.js
 */

import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const manifestPath = resolve(repoRoot, 'custom-elements.json');
const outputPath = resolve(repoRoot, 'dist/types/vue.d.ts');

const PACKAGE = '@nldd/design-system';

const toCamel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const toPascal = (name) => {
	const camel = toCamel(name);
	return camel.charAt(0).toUpperCase() + camel.slice(1);
};

/** One JSDoc line, so hovering a prop in an editor shows what it does. */
function comment(text) {
	return text ? `\n\t\t/** ${String(text).replace(/\s+/g, ' ').replace(/\*\//g, '*\\/')} */` : '';
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const components = [];
for (const module of manifest.modules ?? []) {
	// Only the module is exported, not each element in it, so the type of
	// nldd-menu-item is imported from the path of menu.ts.
	const subpath = module.path.split('/').pop().replace(/\.ts$/, '');
	for (const declaration of module.declarations ?? []) {
		if (!declaration.customElement || !declaration.tagName) continue;
		components.push({ ...declaration, subpath });
	}
}
components.sort((a, b) => a.tagName.localeCompare(b.tagName));

const imports = components
	.map((c) => `import type { ${c.name} } from '${PACKAGE}/${c.subpath}';`)
	.join('\n');

const propsTypes = components
	.map((component) => {
		const lines = [];
		const seen = new Set();

		for (const attribute of component.attributes ?? []) {
			const field = attribute.fieldName ?? toCamel(attribute.name);
			const type = `${component.name}['${field}']`;
			for (const key of [attribute.name, field]) {
				if (seen.has(key)) continue;
				seen.add(key);
				lines.push(`${comment(attribute.description)}\n\t\t'${key}'?: ${type};`);
			}
		}

		// Properties with no attribute behind them: a function or an object, which
		// only travels as a DOM property. Vue binds those with :prop="value".
		const attributeFields = new Set((component.attributes ?? []).map((a) => a.fieldName));
		for (const member of component.members ?? []) {
			if (member.kind !== 'field' || member.static) continue;
			if (member.attribute || attributeFields.has(member.name)) continue;
			if (seen.has(member.name)) continue;
			seen.add(member.name);
			lines.push(`${comment(member.description)}\n\t\t'${member.name}'?: ${component.name}['${member.name}'];`);
		}

		for (const event of component.events ?? []) {
			const key = `on${toPascal(event.name)}`;
			if (seen.has(key)) continue;
			seen.add(key);
			lines.push(`${comment(event.description)}\n\t\t'${key}'?: (event: CustomEvent) => void;`);
		}

		return `\ttype ${component.name}Props = {${lines.join('')}\n\t};`;
	})
	.join('\n\n');

const entries = components
	.map((c) => `${comment(c.description)}\n\t\t'${c.tagName}': DefineComponent<${c.name}Props>;`)
	.join('');

const output = `// Generated by scripts/generate-vue-types.js. Do not edit.
//
// Declares every nldd-* element for Vue's template type-checking. Import it once
// in your project (for example in env.d.ts):
//
//     import '${PACKAGE}/vue';
//
// Every attribute is available both as written in markup (week-numbers) and in
// the form Vue normalises it to (weekNumbers). Events are the prop Vue derives
// from @change, so onChange.

import type { DefineComponent } from 'vue';
${imports}

declare module 'vue' {
${propsTypes}

	export interface GlobalComponents {${entries}
	}
}

export {};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
console.log(`Wrote ${outputPath.replace(`${repoRoot}/`, '')} (${components.length} elements)`);
